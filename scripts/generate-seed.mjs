import { readFileSync, writeFileSync } from 'node:fs';
const { sampleCatalog } = await import('../src/sample.ts');
const q = v => "'"+String(v).replaceAll("'","''")+"'";
const rows = ['-- Fictional sample content only. Generated by npm exec node scripts/generate-seed.mjs.'];
for (const p of sampleCatalog.profiles) rows.push(`INSERT INTO public_profiles VALUES (${[p.id,p.name,p.department,p.year,p.bio,p.initials,1].map(q).join(',')});`);
for (const e of sampleCatalog.entries) rows.push(`INSERT INTO content VALUES (${[e.id,e.kind,e.title,e.summary,e.body,JSON.stringify(e.tags),e.authorId,e.audience,e.prerequisite,e.outcome,e.updatedAt,e.minutes,JSON.stringify(e.relatedIds),'published',1].map(q).join(',')});`);
writeFileSync('migrations/0002_sample_content.sql',rows.join('\n')+'\n');
