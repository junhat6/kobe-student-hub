## 例：CSVの集計に、どの道具を選ぶか

100万行・約18.1MBのCSVを、月とカテゴリごとに集計する道具を考えます。使うのは自分一人、週1回。ツールの起動・import後、CSVを読み込んでから集計結果が10秒以内に出れば十分、という条件を先に決めました。

AIにはDuckDBとSQLiteの候補、同じ集計SQL、比較用コードを出してもらいます。どちらもローカルで使える候補です。DuckDBではCSVを直接SQLで集計し、SQLiteではPythonでCSVをテーブルへ取り込んでから集計します。

同じ問い合わせ方で比べるSQLは、次の集計です。DuckDBでは `events` をCSVのviewにし、SQLiteでは取込先のtableにしています。

```sql
SELECT period, category, COUNT(*) AS rows, SUM(amount_cents) AS amount_cents
FROM events
GROUP BY period, category
ORDER BY period, category;
```

ここで残したい判断は、「100万行だからDuckDB」という結論だけではありません。**今回ほしいのはCSV全体の集計で、入力・更新の画面は要らない。毎週の取込手順を少なくしたい**、という選択の条件です。

### 同じデータで、採用条件を確かめる

生成したCSVについて、月×カテゴリの全96組の件数・合計を比較しました。両方とも、データ生成時に別に計算した期待値と一致しています。

| CSVから最初の集計結果まで | 3回の中央値 |
| --- | --- |
| DuckDB | 0.065秒 |
| SQLite | 0.741秒 |

この実験では**両方とも10秒以内**でした。そこで今回は、CSVを直接扱えて、取込工程を減らせるDuckDBを選びます。SQLiteが性能条件を満たせないから、という判断ではありません。

測定環境はApple M4・16GiB、Python 3.12.12／DuckDB 2.0.0／SQLite 3.50.4です。表は読込・取込を含む手順の比較で、DB単体の一般的な速度順位ではありません。プロセス起動・importは計測外、OSのキャッシュは未制御です。メモリ使用量・同時更新・実データは測っていません。[実験コード・全結果・条件](https://github.com/junhat6/kobe-student-hub/tree/main/experiments/learning-notes-db-choice)を残し、別の条件で使うときに確かめ直せるようにします。

