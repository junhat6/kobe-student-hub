**考えたこと：** 入力された空白まで検索語として照合しているのではないか。前後の空白は入力時の余分なものとして扱い、語の途中の空白は残すことにした。

**試したこと：** 検索前にJavaScriptの `trim()` で検索語の前後の空白を除く処理を加えた。空白を除いた結果が空文字なら、全件を表示する分岐へ進める。

**確かめたこと：** 同じ3件のデータで、修正後の表示件数を確認した、という想定の記録。

- 「制作」→ 2件
- 「 制作 」→ 2件
