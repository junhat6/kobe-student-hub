## なぜ制作ノートを残すのか

完成した画面やコードだけでは、途中で何に困り、どの案を選び、どこまで確かめたかは伝わりにくいものです。「検索を直した」とだけ書いても、時間がたつと直した理由を思い出せないかもしれません。

記録を使う場面を、先に考えてみます。

- **次の制作で使う。** 同じ不具合に出会ったとき、前回の条件と今回の条件を比べ、試す方法を選ぶ材料にする。
- **人に説明する。** チームへの共有や作品紹介で、完成物だけでなく、自分が担当したことと判断の理由を示す。
- **学ぶことを選ぶ。** 確認できたことと予想を分け、説明できない点を次に調べる問いにする。

就活で作品について話すときにも、記録は説明の材料になります。ただし、ノートがあるだけで理解や評価が保証されるわけではありません。実際に自分が行ったことと、確かめた範囲を説明できることが大切です。

## 具体例：「検索を直した」を、後で使える記録にする

